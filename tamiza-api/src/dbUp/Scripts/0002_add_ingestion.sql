-- Kobo ingestion: raw submissions, the synchronization log (which is also the queue) and per-project schedules.

ALTER TABLE tamiza.projects
    ADD COLUMN sync_interval_hours integer NOT NULL DEFAULT 12,
    ADD COLUMN reconcile_interval_hours integer NOT NULL DEFAULT 24,
    ADD COLUMN next_sync_at timestamp with time zone NOT NULL DEFAULT now(),
    ADD COLUMN next_reconcile_at timestamp with time zone NOT NULL DEFAULT (now() + interval '1 day'),
    ADD COLUMN last_webhook_at timestamp with time zone,
    ADD CONSTRAINT ck_projects_sync_interval_hours CHECK (sync_interval_hours BETWEEN 1 AND 168),
    ADD CONSTRAINT ck_projects_reconcile_interval_hours CHECK (reconcile_interval_hours BETWEEN 1 AND 168);

CREATE TABLE tamiza.raw_submissions (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    project_id uuid NOT NULL,
    kobo_id bigint NOT NULL,
    kobo_uuid character varying(128) NOT NULL,
    form_version character varying(128),
    submitted_at timestamp with time zone,
    data jsonb NOT NULL,
    origin character varying(16) NOT NULL,
    received_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    deleted boolean NOT NULL DEFAULT FALSE,
    deleted_at timestamp with time zone,
    CONSTRAINT pk_raw_submissions PRIMARY KEY (id),
    CONSTRAINT ck_raw_submissions_origin CHECK (origin IN ('webhook', 'sync')),
    CONSTRAINT fk_raw_submissions_projects_project_id FOREIGN KEY (project_id) REFERENCES tamiza.projects (id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX ix_raw_submissions_project_id_kobo_id ON tamiza.raw_submissions (project_id, kobo_id);

CREATE INDEX ix_raw_submissions_project_id_kobo_uuid ON tamiza.raw_submissions (project_id, kobo_uuid);

CREATE TABLE tamiza.syncs (
    id uuid NOT NULL,
    project_id uuid NOT NULL,
    kind character varying(16) NOT NULL,
    trigger character varying(16) NOT NULL,
    status character varying(16) NOT NULL,
    requested_by uuid,
    queued_at timestamp with time zone NOT NULL,
    started_at timestamp with time zone,
    finished_at timestamp with time zone,
    created_count integer NOT NULL DEFAULT 0,
    updated_count integer NOT NULL DEFAULT 0,
    deleted_count integer NOT NULL DEFAULT 0,
    error_code character varying(64),
    error text,
    CONSTRAINT pk_syncs PRIMARY KEY (id),
    CONSTRAINT ck_syncs_kind CHECK (kind IN ('incremental', 'full', 'reconciliation')),
    CONSTRAINT ck_syncs_trigger CHECK (trigger IN ('schedule', 'manual', 'initial')),
    CONSTRAINT ck_syncs_status CHECK (status IN ('queued', 'running', 'succeeded', 'failed')),
    CONSTRAINT fk_syncs_projects_project_id FOREIGN KEY (project_id) REFERENCES tamiza.projects (id) ON DELETE CASCADE,
    CONSTRAINT fk_syncs_users_requested_by FOREIGN KEY (requested_by) REFERENCES tamiza.users (id) ON DELETE RESTRICT
);

-- At most one queued or running synchronization per project.
CREATE UNIQUE INDEX ix_syncs_project_id_active ON tamiza.syncs (project_id) WHERE status IN ('queued', 'running');

CREATE INDEX ix_syncs_project_id_queued_at ON tamiza.syncs (project_id, queued_at DESC);

CREATE INDEX ix_syncs_requested_by ON tamiza.syncs (requested_by);
